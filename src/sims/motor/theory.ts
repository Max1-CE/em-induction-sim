export function canTheory(): string {
  return R`
<h3>Теорія: «захоплення» провідника обертовим полем</h3>
<p>Це найпростіша демонстрація принципу асинхронного двигуна: постійний магніт обертається під легкою алюмінієвою банкою (або диском), не торкаючись її. У системі відліку банки поле магніту обертається з відносною кутовою швидкістю $\omega_м - \omega_б$, і в стінках та дні банки індукуються вихрові струми.</p>
<p>За правилом Ленца ці струми протидіють <b>відносному</b> руху. Магніт вони загальмувати не можуть (його крутить двигун), тож захоплюють банку за магнітом. Банка розганяється до швидкості, при якій момент вихрових струмів урівноважує тертя:</p>
${fp(R`M(s) = b\,\omega_б,\qquad s = \frac{\omega_м - \omega_б}{\omega_м} > 0`)}
<p>Струми в банці моделюємо тими самими рамками, що й ротор двигуна: $\frac{L}{c^2}\dot I + RI = \varepsilon$, ${ip(R`$\varepsilon \propto \frac{B_0S}{c}(\omega_м-\omega_б)$`, R`$\varepsilon\propto B_0S(\omega_м-\omega_б)$`)}. Алюміній немагнітний ($\mu\approx1$), тож звичайний магніт його не притягує. Обертовий магніт банку «тягне» лише завдяки індукованим струмам.</p>
<p><b>Спробуйте:</b> збільште тертя — ковзання зросте; зменште опір (мідна банка) — банка відставатиме менше. На цьому ж принципі працює стрілковий спідометр: обертовий магніт захоплює алюмінієвий диск, який повертається проти пружини на кут $\propto\omega$.</p>
`;
}

