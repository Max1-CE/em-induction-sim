export function inductionTheory(): string {
  return R`
<h3>Теорія: асинхронний двигун</h3>
<h4>Обертове магнітне поле</h4>
<p>Три однакові котушки з осями під кутами $0, 120°, 240°$ живляться трифазним струмом $I_j = I_m\cos(\omega t - 2\pi j/3)$. Кожна створює в центрі поле вздовж своєї осі $\hat{\mathbf e}_j$:</p>
$$\mathbf B = B_m\sum_{j=0}^{2}\cos\left(\omega t - \tfrac{2\pi j}{3}\right)\hat{\mathbf e}_j = \tfrac32 B_m(\cos\omega t,\ \sin\omega t).$$
<p>(Доведення: $\sum_j\cos(\omega t - \alpha_j)\cos\alpha_j = \frac32\cos\omega t$ і $\sum_j\cos(\omega t - \alpha_j)\sin\alpha_j = \frac32\sin\omega t$ для $\alpha_j = 2\pi j/3$.) Вектор сталої довжини обертається з кутовою швидкістю $\omega_п = 2\pi f$, і жодна деталь при цьому не рухається.</p>
<h4>Ротор і ковзання</h4>
<p>Ротор «білкова клітка» — це набір замкнених рамок (стрижні + кільця). Для рамки з нормаллю під кутом $\theta_р + \alpha_k$:</p>
${fp(R`\Phi_k = B_0S\cos(\omega_п t - \theta_р - \alpha_k),\quad \varepsilon_k = \frac{B_0S}{c}(\omega_п - \omega_р)\sin(\dots)`, R`\Phi_k = B_0S\cos(\omega_п t - \theta_р - \alpha_k),\quad \varepsilon_k = B_0S(\omega_п - \omega_р)\sin(\dots)`)}
<p>ЕРС пропорційна <b>відносній</b> швидкості поля і ротора. Позначимо ковзання</p>
$$s = \frac{\omega_п - \omega_р}{\omega_п}.$$
<p>Струми ротора змінюються з частотою $s\,\omega_п$ (графік $I_1(t)$). Рівняння рамки — RL-коло, $\frac{L}{c^2}\dot I_k + RI_k = \varepsilon_k$ ${ip('', R`($L\dot I_k + RI_k = \varepsilon_k$)`)}.</p>
<h4>Механічна характеристика M(s)</h4>
<p>Для синусоїдального режиму з частотою $s\omega_п$ (комплексний імпеданс $R + is\omega_пL/c^2$) і $N$ рамок:</p>
${fp(R`M(s) = \frac{N(B_0S/c)^2\,s\omega_п R}{2\left[R^2 + (s\omega_п L/c^2)^2\right]} = \frac{2M_{max}}{s/s_k + s_k/s}`, R`M(s) = \frac{N(B_0S)^2\,s\omega_п R}{2\left[R^2 + (s\omega_п L)^2\right]} = \frac{2M_{max}}{s/s_k + s_k/s}`)}
${fp(R`s_k = \frac{c^2R}{\omega_п L} = \frac{1}{\omega_п T},\qquad M_{max} = \frac{N(B_0S)^2}{4L}`, R`s_k = \frac{R}{\omega_п L} = \frac{1}{\omega_п T},\qquad M_{max} = \frac{N(B_0S)^2}{4L}`)}
<p>Це <b>формула Клосса</b>. При малому $s$ момент лінійний, $M\approx 2M_{max}s/s_k$ — робоча ділянка. При $s > s_k$ індуктивний опір ротора зсуває фазу струму, і момент падає. Якщо навантаження перевищує $M_{max}$, двигун «перекидається» і зупиняється.</p>
<h4>Чому ротор ніколи не досягає синхронної швидкості</h4>
<div class="callout">При $s = 0$ ротор нерухомий <i>відносно поля</i>: потік через рамки сталий, ЕРС нульова, струмів і моменту немає. Індуковані струми, за Ленцом, протидіють <b>відносному руху</b> поля і ротора — тобто тягнуть ротор услід за полем, але лише поки він відстає. Тому асинхронний двигун і називається асинхронним.</div>
<h4>Енергетика</h4>
<p>З $\sum_k\varepsilon_kI_k = M(\omega_п - \omega_р)$: поле віддає потужність $P = M\omega_п$, з неї $M\omega_р = (1-s)P$ йде в механічну роботу, а $sP$ — у тепло в роторі. ККД ротора $\le 1 - s$, тому двигуни працюють при $s\sim 2$–$5\,\%$.</p>
<div class="callout"><b>Модель:</b> рамки ротора незалежні (взаємну індукцію між ними та реакцію ротора на статор не враховано, поле статора задане). Для $N\ge2$ рамок, зсунутих на $\pi/N$, момент не пульсує.</div>
`;
}

